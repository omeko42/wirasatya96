export function isDummySimulationRecord(obj: unknown): boolean {
  if (!obj || typeof obj !== 'object') return false;
  const r = obj as Record<string, unknown>;
  const checkStr = (val: unknown) => String(val || '').trim();
  const checkLower = (val: unknown) => String(val || '').trim().toLowerCase();

  const nrpFields = [
    r.nrp,
    r.oldNrp,
    r.authorNrp,
    r.senderNrp,
    r.receiverNrp,
    r.memberNrp,
    r.targetNrp,
    r.actorNrp,
    r.nrpTerkait,
  ];
  for (const nf of nrpFields) {
    const clean = checkStr(nf);
    if (clean && (DUMMY_NRP_SET.has(clean) || clean.startsWith('999600'))) {
      return true;
    }
  }

  const idStr = checkLower(r.id);
  if (
    idStr.startsWith('ws-dummy-') ||
    idStr.startsWith('u-dummy-') ||
    idStr.startsWith('reg-dummy-') ||
    idStr.startsWith('iur-dummy-') ||
    idStr.startsWith('post-dummy-') ||
    idStr.startsWith('cmt-dummy-') ||
    idStr.startsWith('trx-dummy-') ||
    idStr.startsWith('ast-dummy-') ||
    idStr.startsWith('msg-dummy-') ||
    idStr.startsWith('audit-dummy-') ||
    idStr.includes('9996000')
  ) {
    return true;
  }

  const nameFields = [
    r.nama,
    r.namaLengkap,
    r.authorName,
    r.senderName,
    r.receiverName,
    r.targetNama,
    r.actorName,
    r.penanggungJawab,
    r.pihakTerkait,
  ];
  for (const nm of nameFields) {
    const lower = checkLower(nm);
    if (
      lower &&
      (lower.includes('dummy_') ||
        lower.startsWith('dummy ') ||
        lower.includes('akun contoh') ||
        lower.startsWith('contoh_'))
    ) {
      return true;
    }
  }

  return false;
}

export function isClientDummyCleared(): boolean {
  if (typeof window === 'undefined') return false;
  try {
    if (localStorage.getItem('ws96_dummy_cleared_v1') === 'true') {
      return true;
    }
    const rawDel = localStorage.getItem('ws96_deleted_nrps_v1');
    if (rawDel) {
      const parsed: string[] = JSON.parse(rawDel);
      if (Array.isArray(parsed) && parsed.some((n) => String(n).trim() === '99960001')) {
        return true;
      }
    }
  } catch {
    // ignore
  }
  return false;
}

